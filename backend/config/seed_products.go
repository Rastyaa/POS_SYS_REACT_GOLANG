type SeedProduct struct {
	SKU         string
	Name        string
	Description string
	Price       float64
	Cost        float64
	Stock       int
	Category    string
	Image       string
}

func MigrateAndSeedProducts() {
	var totalCount int
	err := DB.QueryRow("SELECT COUNT(*) FROM products").Scan(&totalCount)
	if err != nil {
		log.Printf("Gagal membaca jumlah produk (mungkin tabel belum dibuat): %v", err)
		return
	}

	var cemilanCount int
	var emptyDescCount int
	_ = DB.QueryRow("SELECT COUNT(*) FROM products WHERE category = 'Cemilan'").Scan(&cemilanCount)
	_ = DB.QueryRow("SELECT COUNT(*) FROM products WHERE description IS NULL OR description = ''").Scan(&emptyDescCount)

	needsReseed := totalCount < 50 || cemilanCount == 0 || emptyDescCount > 0

	if needsReseed {
		log.Println("Data produk belum lengkap (kategori Cemilan/deskripsi kosong). Membersihkan database dan melakukan seeding ulang katalog Restoran Fancy...")

		// Disable constraints / Clear related transactions to prevent foreign key issues
		_, _ = DB.Exec("DELETE FROM sale_items")
		_, _ = DB.Exec("DELETE FROM sales")
		_, err = DB.Exec("DELETE FROM products")
		if err != nil {
			log.Fatalf("Gagal membersihkan tabel produk: %v", err)
		}

		seedData := getFancyMenuData()

		stmt, err := DB.Prepare(`
			INSERT INTO products (sku, name, description, price, cost, stock, category, image)
			VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
		`)
		if err != nil {
			log.Fatalf("Gagal menyiapkan statement insert produk: %v", err)
		}
		defer stmt.Close()

		for _, p := range seedData {
			_, err = stmt.Exec(p.SKU, p.Name, p.Description, p.Price, p.Cost, p.Stock, p.Category, p.Image)
			if err != nil {
				log.Fatalf("Gagal melakukan seeding produk %s: %v", p.Name, err)
			}
		}

		log.Printf("SUCCESS: Berhasil seeding %d produk Restoran Fancy!", len(seedData))
	}
}

